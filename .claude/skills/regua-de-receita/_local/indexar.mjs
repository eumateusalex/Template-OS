// Gera INDEX.md na raiz da skill: uma linha por principio, agrupado por tema.
//
// POR QUE ELE EXISTE
// O maior tema passa de 40 principios e de 20k tokens num unico Read. Abrir o arquivo inteiro para
// citar um principio e desperdicio de contexto. Com o indice, o agente varre todos os titulos
// numa leitura so (o cabecalho do INDEX.md mede quanto custa), escolhe os que precisa, e puxa
// so aqueles blocos com grep.
//
// POR QUE FORA DE references/
// Estrutura DERIVADA se regenera com um comando; estrutura embutida vira divida a cada
// mudanca em references/. Por isso o INDEX.md fica na raiz, irmao do SKILL.md -- e por
// isso a conferencia "12 arquivos de tema" continua verdadeira sem gambiarra.
//
// Rodar: node _local/indexar.mjs [--escreve|--check]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const AQUI = path.dirname(fileURLToPath(import.meta.url));
const SKILL = path.resolve(AQUI, '..');
const REFS = path.join(SKILL, 'references');
const DESTINO = path.join(SKILL, 'INDEX.md');

const ESCREVE = process.argv.includes('--escreve');
const CHECK = process.argv.includes('--check');

// Ordem canonica dos temas, igual a da tabela do README.
const ORDEM = [
  'conversion-and-landing-pages', 'checkout-and-forms', 'onboarding-and-activation',
  'design-philosophy-and-method', 'pricing-and-monetization', 'churn-and-retention',
  'dashboards-and-data-viz', 'behavioral-science-toolkit', 'product-strategy-and-features',
  'positioning-icp-and-gtm', 'ai-era-differentiation', 'metrics-and-experimentation',
];

const refs = fs.readdirSync(REFS).filter((f) => f.endsWith('.md'))
  .map((f) => ({ tema: f.replace('.md', ''), txt: fs.readFileSync(path.join(REFS, f), 'utf8') }));

// O "gatilho" e a resposta curta a pergunta "quando eu abro isso?". Sai do **Apply when.**,
// que e exatamente esse campo, cortado no primeiro fecho de sentido.
function gatilho(bloco) {
  const l = (bloco.match(/^\*\*Apply when\.\*\* (.+)$/m) || [, ''])[1];
  let g = l.split(/[;.]| — /)[0].trim();
  g = g.replace(/^(You are|You're|When|Whenever|Any time)\s+/i, '');
  if (g.length > 78) g = g.slice(0, 75).replace(/\s+\S*$/, '') + '…';
  return g;
}

// O cabecalho se MEDE em vez de afirmar: numero escrito a mao e palpite ate alguem medir.
const kb = (n) => (n / 1024).toFixed(0);
const tamanhos = refs.map((r) => r.txt.length).sort((a, b) => a - b);
const maiorTema = tamanhos[tamanhos.length - 1];

const cabecalho = () => [
  '# Index of principles',
  '',
  '> Generated by `_local/indexar.mjs` — do not edit by hand. Regenerate after any',
  '> change to `references/`, then run `node _local/verificar.js`.',
  '',
  'One line per principle, grouped by theme. Read this first, pick the exact titles you need,',
  'then pull only those blocks (a block runs from its title to the next `## `):',
  '',
  '```bash',
  'grep -F -A 14 "## <exact title>" references/<theme>.md',
  '```',
  '',
  `This index is ~${kb(TAMANHO_FINAL)} KB and covers every principle. The largest single theme` +
    ` file is ~${kb(maiorTema)} KB on its own, so reading a fat theme end to end to cite one`,
  'principle costs more than reading this whole index. Open the full theme file only when you',
  'are sweeping that topic end to end.',
  '',
];

// duas passadas: monta o corpo, mede, e so entao escreve o cabecalho com o numero real
let TAMANHO_FINAL = 0;
const linhas = [];

let total = 0;
const temas = [...refs].sort((a, b) => {
  const ia = ORDEM.indexOf(a.tema), ib = ORDEM.indexOf(b.tema);
  return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib);
});

for (const r of temas) {
  const blocos = r.txt.split(/\n(?=## )/).filter((b) => b.startsWith('## '));
  total += blocos.length;
  linhas.push(`## ${r.tema} (${blocos.length})`);
  linhas.push('');
  for (const b of blocos) {
    const titulo = b.split('\n')[0].slice(3).trim();
    const g = gatilho(b);
    linhas.push(`- **${titulo}**${g ? ` — ${g}` : ''}`);
  }
  linhas.push('');
}

// mede o corpo, depois monta o arquivo com o cabecalho ja sabendo o tamanho real
const corpo = linhas.join('\n').replace(/\n+$/, '\n');
TAMANHO_FINAL = cabecalho().join('\n').length + corpo.length;
const conteudo = (cabecalho().join('\n') + '\n' + corpo).replace(/\n+$/, '\n');

if (CHECK) {
  const atual = fs.existsSync(DESTINO) ? fs.readFileSync(DESTINO, 'utf8') : '';
  if (atual === conteudo) {
    console.log(`INDEX.md em dia — ${total} princípios, ${temas.length} temas`);
    process.exit(0);
  }
  console.log('INDEX.md DEFASADO. Rode: node _local/indexar.mjs --escreve');
  process.exit(1);
}

console.log(`${total} princípios em ${temas.length} temas`);
console.log(`tamanho do índice: ${(conteudo.length / 1024).toFixed(1)} KB (~${Math.round(conteudo.length / 4)} tokens)`);
const maior = temas.map((r) => ({ t: r.tema, n: (r.txt.match(/^## /gm) || []).length }))
  .sort((a, b) => b.n - a.n)[0];
console.log(`maior tema: ${maior.t} com ${maior.n} princípios`);
// O aviso so faz sentido enquanto o quick index NAO existe. Avisar depois de aplicar e
// ruido, e ruido treina quem le a ignorar o proximo aviso de verdade.
const gordos = temas.filter((r) => (r.txt.match(/^## /gm) || []).length > 30);
const semIndice = gordos.filter((r) => !r.txt.includes('quick-index: gerado'));
if (semIndice.length) console.log(`AVISO: ${semIndice.map((r) => r.tema).join(', ')} acima de 30 princípios sem Quick index`);
else if (gordos.length) console.log(`${gordos.length} tema(s) acima de 30 princípios, com Quick index aplicado`);

// QUICK INDEX dentro do arquivo de tema grande.
//
// Acima de 30 principios, quem abre o arquivo inteiro paga a leitura toda antes de saber o
// que tem la. Um sumario no topo resolve, e usa `### ` de proposito: o HEADING_RE do
// contagem de principios e o split do reaplicar.mjs procuram `## `, entao tres
// cerquilhas sao invisiveis para as duas. Reescrito a cada geracao, nunca editado a mao.
const LIMITE = 30;
const MARCA_INI = '<!-- quick-index: gerado por indexar.mjs, nao editar -->';
const MARCA_FIM = '<!-- /quick-index -->';

function aplicaQuickIndex(escreve) {
  let mexidos = 0;
  for (const r of refs) {
    const caminho = path.join(REFS, r.tema + '.md');
    let txt = fs.readFileSync(caminho, 'utf8');
    const fim = (txt.match(/\n*$/) || [''])[0];
    // tira o quick index anterior antes de qualquer decisao
    const limpo = txt.replace(new RegExp(MARCA_INI + '[\\s\\S]*?' + MARCA_FIM + '\\n*', 'g'), '');
    const blocos = limpo.split(/\n(?=## )/).filter((b) => b.startsWith('## '));
    let novo = limpo;
    if (blocos.length > LIMITE) {
      const linhas = [MARCA_INI, '', `### Quick index (${blocos.length})`, ''];
      for (const b of blocos) linhas.push('- ' + b.split('\n')[0].slice(3).trim());
      linhas.push('', MARCA_FIM, '');
      const partes = limpo.split(/\n(?=## )/);
      const cabeca = partes[0].startsWith('## ') ? '' : partes[0];
      novo = (cabeca ? cabeca.replace(/\n*$/, '\n\n') : '') + linhas.join('\n') + blocos.join('\n');
    }
    novo = novo.replace(/\n*$/, fim);
    if (novo !== txt) {
      mexidos++;
      if (escreve) fs.writeFileSync(caminho, novo, 'utf8');
    }
  }
  return mexidos;
}

if (ESCREVE) {
  fs.writeFileSync(DESTINO, conteudo, 'utf8');
  const n = aplicaQuickIndex(true);
  console.log(`\ngravado INDEX.md` + (n ? ` (+ quick index em ${n} tema(s))` : ''));
} else {
  console.log('\nsimulacao. Rode com --escreve para gravar, ou --check para conferir se está em dia.');
}
